/* Round constants: x^(i-1) in GF(2^8) for the 10 AES-128 rounds. */
static const u8 rcon[10] = {
    0x01u, 0x02u, 0x04u, 0x08u, 0x10u,
    0x20u, 0x40u, 0x80u, 0x1Bu, 0x36u,
};

/* ---- Key expansion ---------------------------------------------------- */

void aes128_init(aes128_ctx_t *ctx, const u8 key[AES128_KEY_SIZE])
{
    u8 *rk;
    u32 i;

    if (ctx == NULL || key == NULL) {
        return;
    }
    rk = ctx->round_key;
    for (i = 0u; i < AES128_KEY_SIZE; i++) {
        rk[i] = key[i];
    }

    for (i = AES128_KEY_SIZE; i < AES128_ROUND_KEYS; i += 4u) {
        u8 t0 = rk[i - 4u];
        u8 t1 = rk[i - 3u];
        u8 t2 = rk[i - 2u];
        u8 t3 = rk[i - 1u];

        if ((i % 16u) == 0u) {
            /* RotWord + SubWord + Rcon. */
            u8 first = t0;

            t0 = (u8)(sbox[t1] ^ rcon[i / 16u - 1u]);
            t1 = sbox[t2];
            t2 = sbox[t3];
            t3 = sbox[first];
        }
        rk[i + 0u] = (u8)(rk[i - 16u] ^ t0);
        rk[i + 1u] = (u8)(rk[i - 15u] ^ t1);
        rk[i + 2u] = (u8)(rk[i - 14u] ^ t2);
        rk[i + 3u] = (u8)(rk[i - 13u] ^ t3);
    }
}

/* ---- Round transforms ------------------------------------------------- */

static void add_round_key(u8 s[AES_BLOCK_SIZE], const u8 *rk)
{
    u32 i;

    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        s[i] ^= rk[i];
    }
}

static void sub_bytes(u8 s[AES_BLOCK_SIZE])
{
    u32 i;

    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        s[i] = sbox[s[i]];
    }
}

static void inv_sub_bytes(u8 s[AES_BLOCK_SIZE])
{
    u32 i;

    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        s[i] = inv_sbox[s[i]];
    }
}

/* State is column-major: s[4*col + row]. */
static void shift_rows(u8 s[AES_BLOCK_SIZE])
{
    u8 t;

    /* Row 1: rotate left by 1 (indices 1,5,9,13). */
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    /* Row 2: rotate left by 2 (indices 2,6,10,14). */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* Row 3: rotate left by 3 (indices 3,7,11,15). */
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void inv_shift_rows(u8 s[AES_BLOCK_SIZE])
{
    u8 t;

    /* Inverse of the above: rows rotate right. */
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

/* Multiply in GF(2^8) modulo x^8 + x^4 + x^3 + x + 1 (0x11B). */
static u8 gmul(u8 a, u8 b)
{
    u8 p = 0u;
    u32 i;

    for (i = 0u; i < 8u; i++) {
        if ((b & 1u) != 0u) {
            p ^= a;
        }
        {
            u8 hi = (u8)(a & 0x80u);

            a = (u8)(a << 1);
            if (hi != 0u) {
                a ^= 0x1Bu;
            }
        }
        b >>= 1;
    }
    return p;
}

static void mix_columns(u8 s[AES_BLOCK_SIZE])
{
    u32 c;

    for (c = 0u; c < 4u; c++) {
        u8 *p = s + 4u * c;
        u8 a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];

        p[0] = (u8)(gmul(a0, 0x02u) ^ gmul(a1, 0x03u) ^ a2 ^ a3);
        p[1] = (u8)(a0 ^ gmul(a1, 0x02u) ^ gmul(a2, 0x03u) ^ a3);
        p[2] = (u8)(a0 ^ a1 ^ gmul(a2, 0x02u) ^ gmul(a3, 0x03u));
        p[3] = (u8)(gmul(a0, 0x03u) ^ a1 ^ a2 ^ gmul(a3, 0x02u));
    }
}

static void inv_mix_columns(u8 s[AES_BLOCK_SIZE])
{
    u32 c;

    for (c = 0u; c < 4u; c++) {
        u8 *p = s + 4u * c;
        u8 a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];

        p[0] = (u8)(gmul(a0, 0x0Eu) ^ gmul(a1, 0x0Bu) ^
                    gmul(a2, 0x0Du) ^ gmul(a3, 0x09u));
        p[1] = (u8)(gmul(a0, 0x09u) ^ gmul(a1, 0x0Eu) ^
                    gmul(a2, 0x0Bu) ^ gmul(a3, 0x0Du));
        p[2] = (u8)(gmul(a0, 0x0Du) ^ gmul(a1, 0x09u) ^
                    gmul(a2, 0x0Eu) ^ gmul(a3, 0x0Bu));
        p[3] = (u8)(gmul(a0, 0x0Bu) ^ gmul(a1, 0x0Du) ^
                    gmul(a2, 0x09u) ^ gmul(a3, 0x0Eu));
    }
}

/* ---- Block cipher ----------------------------------------------------- */

void aes128_encrypt_block(const aes128_ctx_t *ctx,
                          const u8 in[AES_BLOCK_SIZE],
                          u8 out[AES_BLOCK_SIZE])
{
    u8 s[AES_BLOCK_SIZE];
    u32 r;
    u32 i;

    if (ctx == NULL || in == NULL || out == NULL) {
        return;
    }
    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        s[i] = in[i];
    }

    add_round_key(s, ctx->round_key);
    for (r = 1u; r < 10u; r++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, ctx->round_key + r * AES_BLOCK_SIZE);
    }
    /* Final round: no MixColumns. */
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, ctx->round_key + 10u * AES_BLOCK_SIZE);

    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        out[i] = s[i];
    }
}

void aes128_decrypt_block(const aes128_ctx_t *ctx,
                          const u8 in[AES_BLOCK_SIZE],
                          u8 out[AES_BLOCK_SIZE])
{
    u8 s[AES_BLOCK_SIZE];
    u32 r;
    u32 i;

    if (ctx == NULL || in == NULL || out == NULL) {
        return;
    }
    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        s[i] = in[i];
    }

    add_round_key(s, ctx->round_key + 10u * AES_BLOCK_SIZE);
    for (r = 9u; r > 0u; r--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, ctx->round_key + r * AES_BLOCK_SIZE);
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, ctx->round_key);

    for (i = 0u; i < AES_BLOCK_SIZE; i++) {
        out[i] = s[i];
    }
}

/* ---- CTR mode --------------------------------------------------------- */

static void ctr_increment(u8 counter[AES_BLOCK_SIZE])
{
    u32 i;

    for (i = AES_BLOCK_SIZE; i > 0u; i--) {
        if (++counter[i - 1u] != 0u) {
            break;
        }
    }
}

void aes128_ctr(const aes128_ctx_t *ctx, u8 counter[AES_BLOCK_SIZE],
                u8 *buf, u32 len)
{
    u8 keystream[AES_BLOCK_SIZE];
    u32 i;

    if (ctx == NULL || counter == NULL || buf == NULL) {
        return;
    }

    while (len != 0u) {
        u32 n = (len < AES_BLOCK_SIZE) ? len : AES_BLOCK_SIZE;

        aes128_encrypt_block(ctx, counter, keystream);
        for (i = 0u; i < n; i++) {
            buf[i] ^= keystream[i];
        }
        buf += n;
        len -= n;
        ctr_increment(counter);
    }
}
